package com.geneinvoice.common.schema;

import com.geneinvoice.automation.rule.TriggerKind;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/** Plain: scratch tables in an H2 database of the test's own, never the application's. */
class SchemaSupportTest {

    enum Shade { LIGHT, DARK, DIM }

    enum TwoShades { LIGHT, DARK }

    Connection connection;

    @BeforeEach
    void open() throws SQLException {
        connection = DriverManager.getConnection("jdbc:h2:mem:schema-support-" + System.nanoTime(), "sa", "");
    }

    @AfterEach
    void close() throws SQLException {
        connection.close();
    }

    @Test
    void theProductIsNamedInLowerCase() throws SQLException {
        assertThat(SchemaSupport.product(connection)).isEqualTo("h2");
    }

    @Test
    void widenAddsTheMissingConstantsToANativeEnumColumnAndKeepsItNotNull() throws SQLException {
        execute("create table swatches (id bigint primary key, shade enum ('LIGHT','DARK') not null)");
        execute("insert into swatches values (1, 'DARK')");
        assertThatThrownBy(() -> execute("insert into swatches values (2, 'DIM')")).isInstanceOf(SQLException.class);

        SchemaSupport.widen(connection, "swatches", "shade", Shade.class);

        execute("insert into swatches values (2, 'DIM')");
        assertThat(strings("select shade from swatches order by id")).containsExactly("DARK", "DIM");
        assertThat(SchemaSupport.isNullable(connection, "swatches", "shade")).isFalse();
        assertThatThrownBy(() -> execute("insert into swatches values (3, null)")).isInstanceOf(SQLException.class);
        assertThat(strings("""
                select v.value_name from information_schema.enum_values v
                  join information_schema.columns c
                    on c.table_name = v.object_name and c.dtd_identifier = v.enum_identifier
                 where c.table_name = 'SWATCHES' and c.column_name = 'SHADE' order by v.value_ordinal
                """)).containsExactly("LIGHT", "DARK", "DIM");
    }

    @Test
    void widenLeavesAnEnumColumnThatAlreadyHasEveryConstantAlone() throws SQLException {
        execute("create table swatches (id bigint primary key, shade enum ('LIGHT','DARK','DIM','EXTRA') not null)");
        execute("insert into swatches values (1, 'EXTRA')");

        SchemaSupport.widen(connection, "swatches", "shade", TwoShades.class);

        assertThat(strings("select shade from swatches")).containsExactly("EXTRA");
        execute("insert into swatches values (2, 'DIM')");
    }

    @Test
    void widenReplacesAStaleCheckConstraint() throws SQLException {
        execute("create table swatches (id bigint primary key, shade varchar(10) not null,"
                + " constraint swatches_shade_check check (shade in ('LIGHT','DARK')))");
        assertThatThrownBy(() -> execute("insert into swatches values (1, 'DIM')")).isInstanceOf(SQLException.class);

        SchemaSupport.widen(connection, "swatches", "shade", Shade.class);

        execute("insert into swatches values (1, 'DIM')");
        assertThatThrownBy(() -> execute("insert into swatches values (2, 'PURPLE')")).isInstanceOf(SQLException.class);
        assertThat(connection.getAutoCommit()).isTrue();
    }

    /** The outbox an earlier build made (MIG-R1-1): its NOT NULLs and CHECKs refused every row this one writes. */
    @Test
    void relaxColumnsLetsALegacyOutboxTakeTheRowsTheCurrentMappingWrites() throws SQLException {
        execute("""
                create table automation_events (
                    id bigint generated by default as identity primary key,
                    attempts integer not null,
                    entity_id bigint not null,
                    entity_type varchar(20) not null,
                    idempotency_key varchar(200) not null,
                    status varchar(20) not null,
                    trigger_kind varchar(20) not null,
                    kind varchar(20) not null,
                    claims integer not null,
                    depth integer not null,
                    occurred_at timestamp with time zone not null,
                    history_tx_id varchar(36),
                    constraint automation_events_entity_type_check check (entity_type in ('CUSTOMER','INVOICE','PAYMENT')),
                    constraint automation_events_status_check
                        check (status in ('QUEUED','RUNNING','DONE','SKIPPED','FAILED')),
                    constraint automation_events_trigger_kind_check
                        check (trigger_kind in ('CREATED','UPDATED','DAILY','WEEKLY')))""");
        String insert = "insert into automation_events (attempts, entity_id, entity_type, idempotency_key, status,"
                + " trigger_kind, kind, claims, depth, occurred_at) values (0, null, 'CUSTOMER', null, 'PENDING',"
                + " null, 'UPDATED', 0, 0, current_timestamp)";
        assertThatThrownBy(() -> execute(insert)).isInstanceOf(SQLException.class);

        Set<String> keep = Set.of("id", "attempts", "claims", "depth", "kind", "occurred_at", "status");
        assertThat(SchemaSupport.relaxColumns(connection, "automation_events", keep, true)).isPositive();

        execute(insert);
        assertThat(strings("select status || ':' || coalesce(idempotency_key, '-') || ':' || coalesce("
                + "cast(entity_id as varchar), '-') from automation_events")).containsExactly("PENDING:-:-");
        assertThat(strings("""
                select constraint_name from information_schema.table_constraints
                 where table_name = 'AUTOMATION_EVENTS' and constraint_type = 'CHECK'""")).isEmpty();
        assertThat(strings("""
                select lower(column_name) from information_schema.columns
                 where table_name = 'AUTOMATION_EVENTS' and is_nullable = 'NO' order by column_name"""))
                .containsExactlyElementsOf(keep.stream().sorted().toList());
        assertThat(connection.getAutoCommit()).isTrue();
        assertThat(SchemaSupport.relaxColumns(connection, "automation_events", keep, true))
                .as("nothing left to do").isZero();
        assertThat(SchemaSupport.relaxColumns(connection, "no_such_table", keep, true)).isZero();
    }

    @Test
    void relaxColumnsDropsOnlyTheChecksOnColumnsTheMappingDoesNotHave() throws SQLException {
        execute("""
                create table automation_rules (
                    id bigint primary key,
                    action varchar(20) not null,
                    run_count bigint not null,
                    name varchar(200) not null,
                    entity_type varchar(20) not null,
                    constraint automation_rules_action_check
                        check (action in ('CREATE_TASK','CREATE_PROMISE','CREATE_DISPUTE','SEND_EMAIL')),
                    constraint automation_rules_entity_type_check check (entity_type in ('CUSTOMER','INVOICE')))""");

        SchemaSupport.relaxColumns(connection, "automation_rules", Set.of("id", "name", "entity_type"),
                Set.of("id", "name", "entity_type"), false);

        assertThat(strings("""
                select constraint_name from information_schema.table_constraints
                 where table_name = 'AUTOMATION_RULES' and constraint_type = 'CHECK'"""))
                .containsExactly("AUTOMATION_RULES_ENTITY_TYPE_CHECK");
        execute("insert into automation_rules (id, name, entity_type) values (1, 'r', 'INVOICE')");
        assertThatThrownBy(() -> execute("insert into automation_rules (id, name, entity_type) values (2, 'r', 'X')"))
                .isInstanceOf(SQLException.class);
        assertThatThrownBy(() -> execute("insert into automation_rules (id, entity_type) values (3, 'INVOICE')"))
                .as("a column the mapping requires stays required").isInstanceOf(SQLException.class);
    }

    /** MIG-R1-2: the earlier build's trigger kinds share no constant with this one's, the first included. */
    @Test
    void widenReplacesALegacyCheckThatListsNoneOfTheCurrentConstants() throws SQLException {
        execute("create table automation_rules (id bigint primary key, trigger_kind varchar(30) not null,"
                + " constraint automation_rules_trigger_kind_check"
                + " check (trigger_kind in ('CREATED','UPDATED','DAILY','WEEKLY')))");
        assertThatThrownBy(() -> execute("insert into automation_rules values (1, 'ENTITY_CREATED')"))
                .isInstanceOf(SQLException.class);

        SchemaSupport.widen(connection, "automation_rules", "trigger_kind", TriggerKind.class);

        execute("insert into automation_rules values (1, 'ENTITY_CREATED')");
        execute("insert into automation_rules values (2, 'MANUAL')");
        assertThatThrownBy(() -> execute("insert into automation_rules values (3, 'BOGUS')"))
                .isInstanceOf(SQLException.class);
        assertThat(connection.getAutoCommit()).isTrue();
    }

    @Test
    void widenLeavesChecksThatAreNotThisColumnsEnumCheckAlone() throws SQLException {
        execute("create table swatches (id bigint primary key, shade varchar(10) not null, other varchar(10),"
                + " constraint swatches_pair_check check (shade in ('LIGHT') or other in ('X')),"
                + " constraint swatches_other_check check (other in ('LIGHT','Y')))");

        SchemaSupport.widen(connection, "swatches", "shade", Shade.class);

        assertThat(strings("""
                select constraint_name from information_schema.table_constraints
                 where table_name = 'SWATCHES' and constraint_type = 'CHECK' order by constraint_name"""))
                .containsExactly("SWATCHES_OTHER_CHECK", "SWATCHES_PAIR_CHECK");
    }

    @Test
    void anEnumCheckIsRecognisedAsPostgresPrintsIt() {
        String pg = "CHECK (((trigger_kind)::text = ANY ((ARRAY['CREATED'::character varying, "
                + "'UPDATED'::character varying])::text[])))";
        assertThat(SchemaSupport.isEnumCheck(pg, "trigger_kind")).isTrue();
        assertThat(SchemaSupport.isEnumCheck(pg, "status")).isFalse();
        assertThat(SchemaSupport.literals(pg)).containsExactly("CREATED", "UPDATED");
        assertThat(SchemaSupport.isEnumCheck("CHECK (((trigger_kind)::text <> 'X'::text))", "trigger_kind"))
                .isFalse();
        assertThat(SchemaSupport.identifiers("CHECK (((action)::text = ANY ((ARRAY['CREATE_TASK'::character varying])"
                + "::text[])))")).contains("action");
    }

    @Test
    void lengthenWidensOnlyTheVarcharColumnsShorterThanTheMapping() throws SQLException {
        execute("create table automation_rules (id bigint primary key, trigger_kind varchar(20) not null,"
                + " name varchar(200), description varchar(50), note text)");
        assertThatThrownBy(() -> execute("insert into automation_rules values (1, 'ENTITY_CREATED_OR_UPDATED',"
                + " null, null, null)")).isInstanceOf(SQLException.class);

        assertThat(SchemaSupport.lengthen(connection, "automation_rules",
                Map.of("trigger_kind", 30L, "name", 120L, "note", 10L, "missing", 5L))).isEqualTo(1);

        execute("insert into automation_rules values (1, 'ENTITY_CREATED_OR_UPDATED', null, null, null)");
        assertThat(strings("""
                select lower(column_name) || ' ' || character_maximum_length || ' ' || is_nullable
                  from information_schema.columns
                 where table_name = 'AUTOMATION_RULES' and column_name in ('TRIGGER_KIND', 'NAME')
                 order by column_name""")).containsExactly("name 200 YES", "trigger_kind 30 NO");
        assertThat(SchemaSupport.lengthen(connection, "automation_rules", Map.of("trigger_kind", 30L))).isZero();
        assertThat(connection.getAutoCommit()).isTrue();
    }

    @Test
    void enforceNotNullWaitsUntilEveryRowHasAValue() throws SQLException {
        execute("create table parcels (id bigint primary key, region_id bigint)");
        execute("insert into parcels values (1, 10), (2, null)");

        assertThat(SchemaSupport.isNullable(connection, "parcels", "region_id")).isTrue();
        assertThat(SchemaSupport.enforceNotNull(connection, "parcels", "region_id")).isFalse();
        assertThat(SchemaSupport.isNullable(connection, "parcels", "region_id")).isTrue();

        execute("update parcels set region_id = 10 where region_id is null");
        assertThat(SchemaSupport.enforceNotNull(connection, "parcels", "region_id")).isTrue();

        assertThat(SchemaSupport.isNullable(connection, "parcels", "region_id")).isFalse();
        assertThatThrownBy(() -> execute("insert into parcels values (3, null)")).isInstanceOf(SQLException.class);
        assertThat(SchemaSupport.enforceNotNull(connection, "parcels", "region_id"))
                .as("already enforced").isTrue();
    }

    private void execute(String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private List<String> strings(String sql) throws SQLException {
        List<String> out = new ArrayList<>();
        try (Statement statement = connection.createStatement(); ResultSet rows = statement.executeQuery(sql)) {
            while (rows.next()) out.add(rows.getString(1));
        }
        return out;
    }
}

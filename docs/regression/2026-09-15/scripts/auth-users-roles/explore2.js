// Discovery of dialog layouts and DOM inputs.
const rt = require('../lib.js');
const D = __dirname;
const dump = (nodes) => nodes.map((n) => `[${n.role}] ${(n.label || n.text).slice(0, 50).replace(/\n/g, '/')} @${n.x},${n.y} ${n.w}x${n.h}`).join('\n');
const inputs = (page) => page.$$eval('input, textarea, [role=textbox], flt-semantics[role=textbox]', (els) => els.map((e) => { const r = e.getBoundingClientRect(); return `${e.tagName} ${e.getAttribute('role')} ${e.getAttribute('aria-label')} @${Math.round(r.x + r.width / 2)},${Math.round(r.y + r.height / 2)} ${Math.round(r.width)}x${Math.round(r.height)}`; }));
(async () => {
  const admin = await rt.adminToken();
  const me = await rt.createStaff(admin, 'VIEWER', 'aurx');
  const tok = await rt.login(me.username, me.password);
  let app = await rt.openApp({ token: tok });
  await rt.tap(app.page, /•/);
  console.log('--- MENU\n' + dump(await rt.semantics(app.page)));
  await rt.shot(app.page, D, 'x-menu');
  await rt.tap(app.page, 'Change password');
  console.log('--- CHPW\n' + dump(await rt.semantics(app.page)));
  console.log('inputs', await inputs(app.page));
  console.log(await rt.shot(app.page, D, 'x-chpw'));
  await app.close();
  app = await rt.openApp({ token: admin });
  await rt.go(app.page, '#/users');
  await rt.tap(app.page, 'New user');
  console.log('--- NEW USER\n' + dump(await rt.semantics(app.page)));
  console.log('inputs', await inputs(app.page));
  console.log(await rt.shot(app.page, D, 'x-newuser'));
  await rt.tap(app.page, 'Cancel');
  await rt.go(app.page, '#/roles');
  await rt.tap(app.page, 'New role');
  const rn = await rt.semantics(app.page);
  console.log('--- NEW ROLE\n' + dump(rn.slice(0, 45)));
  console.log('inputs', await inputs(app.page));
  console.log(await rt.shot(app.page, D, 'x-newrole'));
  await app.close();
})().catch((e) => { console.error(e); process.exit(1); });

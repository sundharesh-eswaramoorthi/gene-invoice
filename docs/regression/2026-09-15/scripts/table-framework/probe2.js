const rt = require('../lib.js');
const S = require('./state.json');
const dump = async (page, tag) => console.log(`--- ${tag}\n` + (await rt.semantics(page)).filter((n) => n.y < 900).map((n) => `[${n.role}] ${(n.label || n.text).replace(/\n/g, '\\n').slice(0, 70)} @${n.x},${n.y} ${n.w}x${n.h}`).join('\n'));
(async () => {
  const admin = await rt.adminToken();
  const app = await rt.openApp({ token: admin });
  const { page } = app;
  await rt.go(page, `#/invoices?size=10&f=${encodeURIComponent('customerId:eq:' + S.A)}`, 5000);
  await rt.tap(page, 'Add filter');
  await dump(page, 'add filter dialog');
  await rt.shot(page, __dirname, 'probe2-dialog');
  const col = (await rt.semantics(page)).find((n) => /Column/.test(n.label || n.text || ''));
  console.log('column node', JSON.stringify(col));
  await page.locator(`flt-semantics[data-rt="${col.i}"]`).dispatchEvent('click');
  await page.waitForTimeout(1200);
  await dump(page, 'column menu');
  await rt.shot(page, __dirname, 'probe2-colmenu');
  await page.keyboard.press('Escape'); await page.waitForTimeout(600);
  await page.keyboard.press('Escape'); await page.waitForTimeout(800);
  await rt.tap(page, '10');
  await dump(page, 'rows menu');
  await rt.shot(page, __dirname, 'probe2-rowsmenu');
  await page.keyboard.press('Escape'); await page.waitForTimeout(800);
  await rt.clickAt(page, 290, 276);
  await dump(page, 'after row checkbox');
  await rt.shot(page, __dirname, 'probe2-selected');
  console.log('apiErrors', JSON.stringify(app.apiErrors), 'pageErrors', JSON.stringify(app.pageErrors));
  await app.close();
})().catch((e) => { console.error(e); process.exit(1); });

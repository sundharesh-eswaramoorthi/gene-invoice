-- The automation_events / automation_rules tables exactly as the user's dev DB has them (pg_dump of
-- gene-invoice-db, from an earlier build), plus a few rows that build would have written. Used by phase C of the
-- migration suite on a baseline-produced database (e2e_migration_seed) to exercise the legacy-row path of
-- AutomationSchemaUpgrade, which the dev DB itself (whose legacy tables are empty) does not reach.
CREATE TABLE public.automation_events (
    id bigint NOT NULL,
    attempts integer NOT NULL,
    created_at timestamp(6) with time zone,
    enqueued_at timestamp(6) with time zone,
    entity_id bigint NOT NULL,
    entity_type character varying(20) NOT NULL,
    idempotency_key character varying(200) NOT NULL,
    last_error character varying(2000),
    next_attempt_at timestamp(6) with time zone,
    rule_id bigint,
    status character varying(20) NOT NULL,
    trigger_kind character varying(20) NOT NULL,
    updated_at timestamp(6) with time zone,
    CONSTRAINT automation_events_entity_type_check CHECK (((entity_type)::text = ANY ((ARRAY['CUSTOMER'::character varying, 'INVOICE'::character varying, 'PAYMENT'::character varying])::text[]))),
    CONSTRAINT automation_events_status_check CHECK (((status)::text = ANY ((ARRAY['QUEUED'::character varying, 'RUNNING'::character varying, 'DONE'::character varying, 'SKIPPED'::character varying, 'FAILED'::character varying])::text[]))),
    CONSTRAINT automation_events_trigger_kind_check CHECK (((trigger_kind)::text = ANY ((ARRAY['CREATED'::character varying, 'UPDATED'::character varying, 'DAILY'::character varying, 'WEEKLY'::character varying])::text[])))
);
ALTER TABLE public.automation_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.automation_events_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1);
CREATE TABLE public.automation_rules (
    id bigint NOT NULL,
    action character varying(20) NOT NULL,
    action_json text,
    created_at timestamp(6) with time zone,
    created_by_user_id bigint,
    description character varying(1000),
    enabled boolean NOT NULL,
    entity_type character varying(20) NOT NULL,
    filters_json text,
    last_run_at timestamp(6) with time zone,
    name character varying(200) NOT NULL,
    run_count bigint NOT NULL,
    trigger_kind character varying(20) NOT NULL,
    updated_at timestamp(6) with time zone,
    CONSTRAINT automation_rules_action_check CHECK (((action)::text = ANY ((ARRAY['CREATE_TASK'::character varying, 'CREATE_PROMISE'::character varying, 'CREATE_DISPUTE'::character varying, 'SEND_EMAIL'::character varying])::text[]))),
    CONSTRAINT automation_rules_entity_type_check CHECK (((entity_type)::text = ANY ((ARRAY['CUSTOMER'::character varying, 'INVOICE'::character varying, 'PAYMENT'::character varying])::text[]))),
    CONSTRAINT automation_rules_trigger_kind_check CHECK (((trigger_kind)::text = ANY ((ARRAY['CREATED'::character varying, 'UPDATED'::character varying, 'DAILY'::character varying, 'WEEKLY'::character varying])::text[])))
);
ALTER TABLE public.automation_rules ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.automation_rules_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1);
ALTER TABLE ONLY public.automation_events ADD CONSTRAINT automation_events_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.automation_rules ADD CONSTRAINT automation_rules_pkey PRIMARY KEY (id);

